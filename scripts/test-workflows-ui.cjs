const path = require('node:path');
const os = require('node:os');
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || path.join(os.tmpdir(), 'nexodocs-workflow-ui/node_modules/playwright'));
const base = process.env.APP_URL || 'http://localhost:4200';
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  page.on('response', async response => { if(response.url().endsWith('/auth/me')) console.log('PROFILE HTTP', response.status()); });
  try {
    await page.goto(base + '/login');
    await page.getByLabel('Organización', { exact: true }).selectOption('20000000-0000-0000-0000-000000000001');
    await page.getByLabel('Correo electrónico', { exact: true }).fill('andres.superadmin@acme.example.invalid');
    await page.getByLabel('Contraseña', { exact: true }).fill('DemoPass123!');
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
    await page.waitForURL(url => !url.pathname.includes('/login'));
    for (const [route, heading] of [['/workflows', 'Todos los workflows'], ['/workflows/tasks', 'Mis tareas'], ['/workflows/pending-review', 'Pendientes de revisión'], ['/workflows/pending-approval', 'Pendientes de aprobación'], ['/workflows/active', 'Workflows activos'], ['/workflows/completed', 'Workflows finalizados'], ['/workflows/templates', 'Plantillas de workflows']]) {
      await page.goto(base + route);
      await page.getByRole('heading', { name: heading, exact: true }).waitFor();
      await page.locator('.wf-state[role="status"]').waitFor({ state: 'hidden' });
      if (await page.locator('.wf-error').count()) throw new Error(route + ': ' + await page.locator('.wf-error').first().innerText());
      console.log('PASS UI ' + route);
    }
    await page.goto(base + '/workflows/active');
    await page.locator('.wf-kanban').waitFor();
    await page.getByRole('button',{name:/Lista/}).click();
    await page.locator('.wf-table-wrap').waitFor();
    await page.getByRole('button',{name:/Kanban/}).click();
    await page.locator('.wf-kanban').waitFor();
    await page.goto(base + '/workflows/completed');
    await page.locator('.wf-completed-metrics').waitFor();
    const completedDetail=page.getByRole('button',{name:'Ver detalle',exact:true}).first();
    if(await completedDetail.count()){await completedDetail.click();await page.locator('.wf-finished-drawer').waitFor();await page.getByRole('button',{name:'Detalle',exact:true}).waitFor();await page.getByRole('button',{name:'Cerrar',exact:true}).click();}
    console.log('PASS UI active Kanban/list and completed drawer');
    await page.goto(base + '/workflows/designer');
    await page.getByRole('heading', { name: 'Diseñador de workflows', exact: true }).waitFor();
    await page.getByRole('button', { name: /Informaci/ }).click();
    const templateName='Plantilla UI '+Date.now();
    await page.locator('.wf-template-form').getByLabel('Nombre', { exact: true }).fill(templateName);
    await page.locator('.wf-template-form select').nth(1).selectOption('ACTIVE');
    await page.getByRole('button', { name: /Vista previa/ }).click();
    await page.locator('.wf-designer.preview').waitFor();
    await page.getByRole('button', { name: /Editar/ }).click();
    await page.getByRole('button', { name: /Guardar como plantilla/ }).click();
    await page.locator('app-workflow-designer .wf-success').waitFor();
    await page.waitForFunction(() => parseFloat(getComputedStyle(document.querySelector('.workspace')).paddingLeft) >= 255);
    await page.screenshot({ path: path.join(os.tmpdir(), 'nexodocs-workflow-designer.png'), animations: 'disabled' });
    console.log('LAYOUT', await page.locator('.workspace').evaluate(el => ({padding:getComputedStyle(el).paddingLeft,width:el.getBoundingClientRect().width,viewport:innerWidth,styles:document.styleSheets.length})));
    await page.getByRole('button', { name: /Informaci/ }).click();
    await page.locator('.wf-template-form').getByLabel('Descripción', { exact: true }).fill('Cambio sin guardar');
    const workflowMenu=page.locator('.nav-item').filter({hasText:'Workflows'}).first();
    if(!(await page.locator('a[href="/workflows"]').count()))await workflowMenu.click();
    await page.locator('a[href="/workflows"]').first().click();
    await page.getByRole('heading', { name: 'Hay cambios sin guardar', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Descartar y salir', exact: true }).click();
    await page.waitForURL(base + '/workflows');
    await page.getByRole('button', { name: /Iniciar workflow/ }).click();
    await page.getByRole('heading', { name: 'Seleccionar origen', exact: true }).waitFor();
    await page.getByRole('dialog').locator('select').first().selectOption('INDEPENDENT');
    await page.getByRole('dialog').getByLabel('Nombre del workflow', { exact: true }).fill('Proceso desde UI');
    await page.getByRole('button', { name: 'Continuar', exact: true }).click();
    await page.getByRole('heading', { name: 'Plantilla', exact: true }).waitFor();
    const option=page.getByRole('dialog').locator('select option').filter({hasText:templateName});
    await option.waitFor({state:'attached'});
    await page.getByRole('dialog').locator('select').first().selectOption(await option.getAttribute('value'));
    await page.getByRole('button',{name:'Continuar',exact:true}).click();
    await page.getByRole('heading',{name:'Responsables',exact:true}).waitFor();
    const ownId=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('nexodocs.auth_user')).id);
    for(const assignee of await page.getByRole('dialog').locator('select').all()) await assignee.selectOption(ownId);
    await page.getByRole('button',{name:'Continuar',exact:true}).click();
    await page.getByRole('heading',{name:'Fechas',exact:true}).waitFor();
    await page.getByRole('button',{name:'Continuar',exact:true}).click();
    await page.getByRole('heading',{name:'Resumen',exact:true}).waitFor();
    await page.getByRole('button',{name:'Continuar',exact:true}).click();
    await page.getByRole('heading',{name:'Confirmación',exact:true}).waitFor();
    await page.getByRole('button',{name:'Confirmar e iniciar',exact:true}).click();
    await page.getByText(/Workflow iniciado:/).waitFor();
    const timer=page.locator('.wf-elapsed-duration');
    await timer.waitFor();
    const timerBefore=(await timer.innerText()).trim();
    await page.waitForTimeout(1200);
    const timerAfter=(await timer.innerText()).trim();
    if(timerBefore===timerAfter) throw new Error('Workflow elapsed-time counter did not advance');
    console.log('PASS UI active workflow elapsed-time counter',timerBefore,'→',timerAfter);
    await page.getByRole('dialog').getByRole('button',{name:'Cerrar',exact:true}).click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(base + '/workflows/tasks');
    await page.getByRole('heading', { name: 'Mis tareas', exact: true }).waitFor();
    await page.screenshot({ path: path.join(os.tmpdir(), 'nexodocs-workflow-mobile.png'), fullPage: true });
    if (errors.length) throw new Error(errors.join('\n'));
    console.log('PASS UI designer validation/save, unsaved changes dialog, wizard and mobile');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
