package com.lta.gestdocum.backend.security;

import java.util.UUID;

/** Request-scoped tenant routing context derived only from a validated server identity. */
public final class TenantDatabaseContext {
    private static final ThreadLocal<Route> CURRENT = new ThreadLocal<>();

    private TenantDatabaseContext() { }

    public static Route current() { return CURRENT.get(); }

    public static Scope useTenant(UUID tenantId) {
        return set(new Route(tenantId, null));
    }

    /** Internal control-plane scope for lifecycle operations and tenant lookup. */
    public static Scope useControl() {
        return set(new Route(null, null));
    }

    /** Internal bootstrap scope for a database name generated by TenantDatabaseName. */
    public static Scope useDatabase(UUID tenantId, String databaseName) {
        return set(new Route(tenantId, databaseName));
    }

    private static Scope set(Route route) {
        Route previous = CURRENT.get();
        CURRENT.set(route);
        return () -> {
            if (previous == null) CURRENT.remove();
            else CURRENT.set(previous);
        };
    }

    public record Route(UUID tenantId, String databaseNameOverride) { }

    @FunctionalInterface
    public interface Scope extends AutoCloseable {
        @Override void close();
    }
}
